const ATTRIBUTES = ["aria-label", "title", "placeholder"] as const;

function wrap(original:string, translated:string):string {
  // preserve surrounding whitespace exactly as authored
  const lead = original.slice(0, original.length - original.trimStart().length);
  const trail = original.slice(original.trimEnd().length);
  return lead + translated + trail;
}

function translateText(value:string):string {
  if (current === "en") return value;
  const table = TABLES[current];
  const trimmed = value.trim();
  const direct = table.strings[trimmed];
  if (direct) return wrap(value, direct);
  // composite patterns: "<Name> from this favorite view", counts, stats line
  let match = trimmed.match(/^(.*?)\s+from this favorite view$/);
  if (match) return table.grammar.fromThisView(match[1]);
  match = trimmed.match(/^(\d+) items?$/);
  if (match) return table.grammar.itemCount(Number(match[1]));
  match = trimmed.match(/^Images:\s*(\d+)\s*·\s*Videos:\s*(\d+)$/);
  if (match) return table.grammar.statsLine(match[1], match[2]);
  match = trimmed.match(/^Loading (\d+) of (\d+)…$/);
  if (match) return table.grammar.loadingOf(match[1], match[2]);
  return value;
}

function translateAttribute(name:string, value:string):string {
  if (!value || current === "en") return value;
  const table = TABLES[current];
  const trimmed = value.trim();
  const direct = table.strings[trimmed];
  if (direct) return wrap(value, direct);
  // "<Action> <Name>" composites used in aria-labels
  let match = trimmed.match(/^(Open|Remove|Select|Manage favorite views for|Delete)\s+(.+)$/);
  if (match) {
    if (match[1] === "Manage favorite views for") return table.grammar.manageViewsFor(match[2]);
    return `${table.grammar.verbs[match[1] as keyof typeof table.grammar.verbs]} ${match[2]}`;
  }
  match = trimmed.match(/^(Library menu|Folder menu|Favorite view menu)\s+(.+)$/);
  if (match) {
    const noun = {"Library menu":table.grammar.menus.library, "Folder menu":table.grammar.menus.folder, "Favorite view menu":table.grammar.menus.view}[match[1]];
    return `${noun} ${match[2]}`;
  }
  match = trimmed.match(/^(Newest|Oldest) first: (.+)$/);
  if (match) return table.grammar.sortedFirst(match[1] as "Newest"|"Oldest", match[2]);
  return value;
}

function translateElement(element:Element) {
  for (const attr of ATTRIBUTES) {
    const value = element.getAttribute(attr);
    if (!value) continue;
    const translated = translateAttribute(attr, value);
    if (translated !== value) element.setAttribute(attr, translated);
  }
}

function walk(root:Node) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  // include the root itself when it is an element
  if (root.nodeType === Node.ELEMENT_NODE) translateElement(root as Element);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.nodeType === Node.TEXT_NODE) {
      const text = node.nodeValue ?? "";
      if (!text.trim()) continue;
      const parent = node.parentElement;
      if (parent && (parent.tagName === "CODE" || parent.tagName === "SCRIPT" || parent.tagName === "STYLE")) continue;
      const translated = translateText(text);
      if (translated !== text) node.nodeValue = translated;
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      translateElement(node as Element);
    }
  }
}

let observer: MutationObserver | null = null;

// Installs the live translator once; safe to call repeatedly. When the active
// language is English it disconnects any previous instance.
export function installDomTranslation() {
  if (typeof document === "undefined") return;
  if (current === "en") {
    observer?.disconnect();
    observer = null;
    return;
  }
  if (observer) {
    // Already observing; still walk once so a freshly remounted tree in the
    // new language gets translated even before the first mutation.
    walk(document.body);
    return;
  }
  walk(document.body);
  observer = new MutationObserver(mutations => {
    if (current === "en") return;
    for (const mutation of mutations) {
      switch (mutation.type) {
        case "childList":
          mutation.addedNodes.forEach(node => walk(node));
          break;
        case "attributes":
          if (mutation.target.nodeType === Node.ELEMENT_NODE) {
            translateElement(mutation.target as Element);
            walk(mutation.target);
          }
          break;
        case "characterData":
          if (mutation.target.nodeType === Node.TEXT_NODE) {
            const text = mutation.target.nodeValue ?? "";
            const translated = translateText(text);
            if (translated !== text) mutation.target.nodeValue = translated;
          }
          break;
      }
    }
  });
  observer.observe(document.body, {childList:true, subtree:true, attributes:true, attributeFilter:[...ATTRIBUTES], characterData:true});
}
