// Multilanguage support for the SPA.
//
// The application keeps its canonical strings in English inside the sources
// (tests and e2e suites assert them). Translations are applied at render time:
// curated per-language tables walk the live DOM (initial pass +
// MutationObserver) and rewrite text nodes and common attributes. This yields
// full coverage, including dynamically mounted menus, dialogs and virtual
// lists, without touching every component literal.

export type LanguageSetting = "auto" | "en" | "ua" | "de" | "nl" | "fi" | "sv" | "pl" | "che" | "slo" | "hu" | "es" | "it" | "sl" | "no" | "pt";
export type Lang = Exclude<LanguageSetting, "auto">;

export const LANGUAGES: {id:Lang; label:string}[] = [
  {id:"en", label:"English"},
  {id:"ua", label:"Українська"},
  {id:"de", label:"Deutsch"},
  {id:"nl", label:"Nederlands"},
  {id:"pl", label:"Polski"},
  {id:"che", label:"Čeština"},
  {id:"slo", label:"Slovenčina"},
  {id:"hu", label:"Magyar"},
  {id:"fi", label:"Suomi"},
  {id:"sv", label:"Svenska"},
  {id:"es", label:"Español"},
  {id:"it", label:"Italiano"},
  {id:"sl", label:"Slovenščina"},
  {id:"no", label:"Norsk bokmål"},
  {id:"pt", label:"Português"},
];

const listeners = new Set<() => void>();
let setting: LanguageSetting = "auto";
let current: Lang = detectBrowser();

function detectBrowser(): Lang {
  const locale = typeof navigator !== "undefined" ? navigator.language?.toLowerCase() ?? "" : "";
  if (locale.startsWith("uk")) return "ua";
  if (locale.startsWith("de")) return "de";
  if (locale.startsWith("nl")) return "nl";
  if (locale.startsWith("pl")) return "pl";
  if (locale.startsWith("cs")) return "che";
  if (locale.startsWith("sk")) return "slo";
  if (locale.startsWith("hu")) return "hu";
  if (locale.startsWith("fi")) return "fi";
  if (locale.startsWith("sv")) return "sv";
  if (locale.startsWith("es")) return "es";
  if (locale.startsWith("it")) return "it";
  if (locale.startsWith("sl")) return "sl";
  if (locale.startsWith("nb") || locale.startsWith("nn") || locale.startsWith("no")) return "no";
  if (locale.startsWith("pt")) return "pt";
  return "en";
}

export function resolvedLanguage(): Lang {
  return current;
}

export function currentSetting(): LanguageSetting {
  return setting;
}

// Applies the stored user preference ("auto" follows the browser locale).
// Returns true when the resolved language changed.
export function applyLanguageSetting(value: unknown): boolean {
  const ids = LANGUAGES.map(entry => entry.id);
  const nextSetting: LanguageSetting = value === "auto" || ids.includes(value as Lang) ? value as LanguageSetting : "auto";
  const nextLang: Lang = nextSetting === "auto" ? detectBrowser() : nextSetting;
  setting = nextSetting;
  if (nextLang === current) return false;
  current = nextLang;
  listeners.forEach(listener => listener());
  return true;
}

export function onLanguageChange(listener: () => void): () => void {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}

// Reactive hook for components that must re-render on language switches.
import { useEffect, useState } from "react";
export function useLanguage(): Lang {
  const [lang, setLang] = useState(current);
  useEffect(() => onLanguageChange(() => setLang(current)), []);
  return lang;
}

